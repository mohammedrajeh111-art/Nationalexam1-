import React, { useState, useEffect } from 'react';
import {
  MedicalQuestion,
  SpecialtyKey,
  SPECIALTY_INFO,
} from './data/questionBank';
import { Header, AppTab } from './components/Header';
import { CountdownCard } from './components/CountdownCard';
import { MotivationalHero } from './components/MotivationalHero';
import { SpecialtySelector } from './components/SpecialtySelector';
import { QuestionCard } from './components/QuestionCard';
import { AiMedicalConsultant } from './components/AiMedicalConsultant';
import { MockExamModal } from './components/MockExamModal';
import { BookmarksAndMistakes } from './components/BookmarksAndMistakes';
import { PsychologicalSupport } from './components/PsychologicalSupport';
import {
  Sparkles,
  Bot,
  Award,
  BookOpen,
  CheckCircle,
  XCircle,
  HelpCircle,
  Layers,
  Heart,
  Calendar,
} from 'lucide-react';

export default function App() {
  const [activeTab, setActiveTab] = useState<AppTab>('practice');
  const [isEyeComfortDark, setIsEyeComfortDark] = useState<boolean>(() => {
    return localStorage.getItem('tabibi_theme') === 'dark';
  });

  // Selected specialty
  const [selectedSpecialty, setSelectedSpecialty] = useState<SpecialtyKey | 'comprehensive'>('internal_medicine');

  // Question pool strictly generated by AI (no pre-saved static questions)
  const [questionPool, setQuestionPool] = useState<MedicalQuestion[]>([]);
  const [currentQuestionIndex, setCurrentQuestionIndex] = useState<number>(0);

  // Anti-duplication tracking
  const [seenTopics, setSeenTopics] = useState<string[]>([]);
  const [previousQuestionSnippets, setPreviousQuestionSnippets] = useState<string[]>([]);

  // AI Generation State
  const [isGeneratingAi, setIsGeneratingAi] = useState<boolean>(false);
  const [aiNotice, setAiNotice] = useState<{ message: string; type: 'success' | 'info' | 'error' } | null>(null);

  // Bookmarks & Mistakes (Only user-generated during their live session)
  const [bookmarkedIds, setBookmarkedIds] = useState<string[]>(() => {
    const saved = localStorage.getItem('tabibi_bookmarks');
    return saved ? JSON.parse(saved) : [];
  });

  const [mistakeQuestions, setMistakeQuestions] = useState<MedicalQuestion[]>(() => {
    const saved = localStorage.getItem('tabibi_mistakes');
    return saved ? JSON.parse(saved) : [];
  });

  // Mock Exam Modal State
  const [isMockExamOpen, setIsMockExamOpen] = useState<boolean>(false);

  // Stats
  const [solvedCount, setSolvedCount] = useState<number>(0);
  const [correctCount, setCorrectCount] = useState<number>(0);

  // Sync theme
  useEffect(() => {
    if (isEyeComfortDark) {
      document.documentElement.classList.add('dark');
      localStorage.setItem('tabibi_theme', 'dark');
    } else {
      document.documentElement.classList.remove('dark');
      localStorage.setItem('tabibi_theme', 'light');
    }
  }, [isEyeComfortDark]);

  // Sync bookmarks
  useEffect(() => {
    localStorage.setItem('tabibi_bookmarks', JSON.stringify(bookmarkedIds));
  }, [bookmarkedIds]);

  // Sync mistakes
  useEffect(() => {
    localStorage.setItem('tabibi_mistakes', JSON.stringify(mistakeQuestions));
  }, [mistakeQuestions]);

  // Keep all AI-generated questions in memory for bookmarks and review
  const [allGeneratedQuestions, setAllGeneratedQuestions] = useState<Record<string, MedicalQuestion>>({});

  // Generate dynamic question using Gemini AI (with anti-duplication)
  const handleGenerateAiQuestion = async (
    specialty: SpecialtyKey | 'comprehensive',
    subtopic?: string
  ) => {
    setIsGeneratingAi(true);
    setAiNotice(null);

    try {
      const response = await fetch('/api/generate-question', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          specialty,
          subtopic,
          excludeTopics: seenTopics,
          previousQuestionSnippets: previousQuestionSnippets.slice(-10),
        }),
      });

      const rawText = await response.text();
      let json: any = null;
      try {
        json = JSON.parse(rawText);
      } catch (_err) {
        throw new Error('حدث ضغط مؤقت على الخادم، يرجى النقر على زر التوليد للمحاولة فوراً.');
      }

      if (!response.ok || !json || !json.success) {
        throw new Error(json?.error || 'تعذر توليد السؤال بواسطة الذكاء الاصطناعي');
      }

      const newQ: MedicalQuestion = json.data;

      // Track to strictly prevent repetition
      if (newQ.subtopic) {
        setSeenTopics((prev) => [...prev.slice(-15), newQ.subtopic]);
      }
      setPreviousQuestionSnippets((prev) => [
        ...prev.slice(-15),
        `${newQ.subtopic || ''}: ${newQ.question.slice(0, 40)}`,
      ]);

      // Save to allGenerated map
      setAllGeneratedQuestions((prev) => ({ ...prev, [newQ.id]: newQ }));

      // Add to front of pool and switch to practice tab
      setQuestionPool((prev) => [newQ, ...prev]);
      setCurrentQuestionIndex(0);
      setActiveTab('practice');
      setAiNotice({
        message: `✨ تم توليد حالة سريرية جديدة وحصرية بالذكاء الاصطناعي: ${newQ.subtopic || newQ.specialtyArabic}`,
        type: 'success',
      });
      setTimeout(() => setAiNotice(null), 3500);
    } catch (err: any) {
      console.error(err);
      setAiNotice({
        message: 'حدث ضغط على خادم الذكاء الاصطناعي، انقر على توليد سؤال لإعادة المحاولة فوراً.',
        type: 'error',
      });
    } finally {
      setIsGeneratingAi(false);
    }
  };

  // When specialty changes, immediately generate a fresh AI question for it
  const handleSelectSpecialty = (specialty: SpecialtyKey | 'comprehensive') => {
    setSelectedSpecialty(specialty);
    handleGenerateAiQuestion(specialty);
  };

  // Automatically generate the very first question via AI on initial mount
  useEffect(() => {
    handleGenerateAiQuestion('internal_medicine');
  }, []);

  const handleNextQuestion = () => {
    if (currentQuestionIndex < questionPool.length - 1) {
      setCurrentQuestionIndex((prev) => prev + 1);
    } else {
      // Loop or request AI generation
      handleGenerateAiQuestion(selectedSpecialty);
    }
  };

  const handlePreviousQuestion = () => {
    if (currentQuestionIndex > 0) {
      setCurrentQuestionIndex((prev) => prev - 1);
    }
  };

  const toggleBookmark = (id: string) => {
    setBookmarkedIds((prev) =>
      prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]
    );
  };

  const handleAnswerSelected = (isCorrect: boolean, _selectedIdx: number) => {
    setSolvedCount((prev) => prev + 1);
    const activeQ = questionPool[currentQuestionIndex];

    if (isCorrect) {
      setCorrectCount((prev) => prev + 1);
    } else if (activeQ) {
      // Add to mistakes if not already present
      setMistakeQuestions((prev) => {
        if (prev.some((q) => q.id === activeQ.id)) return prev;
        return [activeQ, ...prev];
      });
    }
  };

  const activeQuestion: MedicalQuestion | undefined = questionPool[currentQuestionIndex];

  const bookmarkedQuestions = Object.values(allGeneratedQuestions).filter((q) =>
    bookmarkedIds.includes(q.id)
  );

  return (
    <div
      dir="rtl"
      className={`min-h-screen flex flex-col font-sans transition-colors duration-200 ${
        isEyeComfortDark
          ? 'bg-slate-950 text-slate-100 selection:bg-blue-900 selection:text-white'
          : 'bg-gradient-to-b from-sky-50/40 via-slate-50 to-blue-50/30 text-slate-800'
      }`}
    >
      {/* Top Navigation Header */}
      <Header
        activeTab={activeTab}
        onTabChange={setActiveTab}
        isEyeComfortDark={isEyeComfortDark}
        onToggleEyeComfort={() => setIsEyeComfortDark((prev) => !prev)}
        onOpenMockExam={() => setIsMockExamOpen(true)}
        bookmarksCount={bookmarkedIds.length}
      />

      <main className="flex-1 max-w-7xl w-full mx-auto px-4 sm:px-6 lg:px-8 py-6 space-y-6">
        {/* Countdown Card (Required: Remaining duration in days to 22/12/2026) */}
        <CountdownCard />

        {/* Motivational Section (Required: Displays motivational quotes upon opening) */}
        <MotivationalHero />

        {/* AI Notification banner if any */}
        {aiNotice && (
          <div
            className={`rounded-xl p-3.5 text-xs flex items-center justify-between border transition-all duration-300 animate-in fade-in slide-in-from-top-2 ${
              aiNotice.type === 'success'
                ? 'bg-emerald-50 text-emerald-900 border-emerald-300'
                : aiNotice.type === 'error'
                ? 'bg-rose-50 text-rose-900 border-rose-300'
                : 'bg-blue-50 text-blue-900 border-blue-200'
            }`}
          >
            <div className="flex items-center gap-2 font-semibold">
              <span>{aiNotice.message}</span>
            </div>
            <button
              onClick={() => setAiNotice(null)}
              className="text-slate-600 hover:text-slate-900 font-bold px-2 py-0.5 hover:underline cursor-pointer"
            >
              إغلاق
            </button>
          </div>
        )}

        {/* Tab 1: Practice Questions across the 6 specialties */}
        {activeTab === 'practice' && (
          <div className="space-y-6">
            {/* Specialty Selector with 6 requested options */}
            <SpecialtySelector
              selectedSpecialty={selectedSpecialty}
              onSelectSpecialty={handleSelectSpecialty}
              onGenerateAiQuestion={handleGenerateAiQuestion}
              isGeneratingAi={isGeneratingAi}
            />

            {/* Active Clinical MCQ Question Card */}
            {isGeneratingAi && !activeQuestion ? (
              <div className="bg-white rounded-2xl border border-blue-200 p-8 sm:p-12 text-center space-y-4 shadow-sm animate-pulse">
                <div className="w-12 h-12 rounded-2xl bg-blue-100 text-blue-600 flex items-center justify-center mx-auto">
                  <Bot className="w-6 h-6 animate-spin" />
                </div>
                <h4 className="text-base sm:text-lg font-bold text-slate-800">
                  جاري صياغة حالة سريرية فريدة بالذكاء الاصطناعي...
                </h4>
                <p className="text-xs sm:text-sm text-slate-500 max-w-md mx-auto">
                  يقوم الذكاء الاصطناعي بتركيب سيناريو سريري حقيقي بمستوى امتحان التخرج الوطني (أتمتة من 5 خيارات مع شروح سريرية ولؤلؤة امتحانية).
                </p>
              </div>
            ) : activeQuestion ? (
              <div className="relative">
                {isGeneratingAi && (
                  <div className="absolute inset-0 z-20 bg-white/70 backdrop-blur-xs rounded-2xl flex flex-col items-center justify-center gap-2">
                    <div className="w-8 h-8 border-3 border-blue-600 border-t-transparent rounded-full animate-spin" />
                    <span className="text-xs font-bold text-blue-900">
                      جاري توليد سؤال جديد غير مكرر...
                    </span>
                  </div>
                )}
                <QuestionCard
                  question={activeQuestion}
                  onNextQuestion={handleNextQuestion}
                  onPreviousQuestion={handlePreviousQuestion}
                  hasPrevious={currentQuestionIndex > 0}
                  questionNumber={currentQuestionIndex + 1}
                  totalQuestions={questionPool.length}
                  onBookmarkToggle={toggleBookmark}
                  isBookmarked={bookmarkedIds.includes(activeQuestion.id)}
                  onAnswerSelected={handleAnswerSelected}
                />
              </div>
            ) : (
              <div className="text-center py-12 bg-white rounded-2xl border border-slate-200 p-6 space-y-3">
                <p className="text-slate-600 font-bold">لا يوجد أسئلة حالياً، اضغط لتوليد سؤال جديد بالذكاء الاصطناعي</p>
                <button
                  onClick={() => handleGenerateAiQuestion(selectedSpecialty)}
                  className="px-5 py-2.5 rounded-xl bg-blue-600 text-white font-bold text-xs shadow-md"
                >
                  توليد سؤال جديد الآن
                </button>
              </div>
            )}
          </div>
        )}

        {/* Tab 2: Ask AI Medical Consultant */}
        {activeTab === 'ai_consult' && (
          <AiMedicalConsultant defaultSpecialty={selectedSpecialty} />
        )}

        {/* Tab 3: Psychological Support Corner (New!) */}
        {activeTab === 'psych_support' && (
          <PsychologicalSupport />
        )}

        {/* Tab 4: Mock Exam Launcher View */}
        {activeTab === 'mock_exam' && (
          <div className="bg-white rounded-2xl border border-slate-200 p-6 sm:p-8 space-y-6 text-center">
            <div className="w-16 h-16 rounded-3xl bg-blue-100 text-blue-700 flex items-center justify-center mx-auto shadow-inner">
              <Award className="w-8 h-8" />
            </div>

            <div className="max-w-xl mx-auto space-y-2">
              <h3 className="text-xl sm:text-2xl font-black text-slate-800">
                محاكاة الامتحان الوطني الموحد (Mock Exam)
              </h3>
              <p className="text-xs sm:text-sm text-slate-500 leading-relaxed">
                اختبار تجريبي مكون من 10 أسئلة سريرية مختلطة تحاكي تماماً توزيع الامتحان الوطني الموحد (باطنة، جراحة، نسائية، أطفال، أذنية، وعينية) مع عداد زمني وتصحيح تفصيلي فوري.
              </p>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 max-w-lg mx-auto text-xs text-slate-700">
              <div className="p-3 rounded-xl bg-blue-50 border border-blue-100 font-semibold">
                ⏱️ 90 ثانية لكل سؤال
              </div>
              <div className="p-3 rounded-xl bg-blue-50 border border-blue-100 font-semibold">
                📊 تقييم سريري ونسبة مئوية
              </div>
              <div className="p-3 rounded-xl bg-blue-50 border border-blue-100 font-semibold">
                🎯 شامل لكافة المواد
              </div>
            </div>

            <button
              onClick={() => setIsMockExamOpen(true)}
              className="inline-flex items-center gap-2 px-8 py-3 rounded-xl bg-gradient-to-r from-blue-600 to-indigo-600 hover:from-blue-700 hover:to-indigo-700 text-white font-bold text-sm sm:text-base shadow-lg shadow-blue-500/25 active:scale-95 transition cursor-pointer"
            >
              <span>بدء الامتحان التجريبي الآن</span>
              <Sparkles className="w-4 h-4 text-yellow-300" />
            </button>
          </div>
        )}

        {/* Tab 4: Bookmarks & Review Mistakes */}
        {activeTab === 'bookmarks' && (
          <BookmarksAndMistakes
            bookmarkedQuestions={bookmarkedQuestions}
            mistakeQuestions={mistakeQuestions}
            onRemoveBookmark={toggleBookmark}
            onClearMistakes={() => setMistakeQuestions([])}
          />
        )}
      </main>

      {/* Mock Exam Modal */}
      <MockExamModal
        isOpen={isMockExamOpen}
        onClose={() => setIsMockExamOpen(false)}
        questions={
          Object.values(allGeneratedQuestions).length > 0
            ? Object.values(allGeneratedQuestions)
            : questionPool
        }
      />

      {/* Eye-Comfort Footer */}
      <footer className="mt-auto border-t border-slate-200/80 bg-white/60 dark:bg-slate-900/60 backdrop-blur-xs py-6 text-center text-xs text-slate-500 dark:text-slate-400">
        <div className="max-w-7xl mx-auto px-4 flex flex-col sm:flex-row items-center justify-between gap-3">
          <div className="flex items-center gap-2">
            <span className="w-2 h-2 rounded-full bg-emerald-500" />
            <span>موعد الامتحان الوطني الموحد: <strong>22 كانون الأول 2026</strong></span>
          </div>

          <div className="flex items-center gap-1.5 text-slate-400">
            <span>صُمم بعناية لراحة عين طالب الطب في درجات اللون الأزرق الطبي الهادئ</span>
            <Heart className="w-3.5 h-3.5 text-rose-400 fill-rose-400 inline" />
          </div>
        </div>
      </footer>
    </div>
  );
}
